import { test, expect } from '@playwright/test';
import { readdir, readFile } from 'fs/promises';
import { resolve } from 'path';
import { randomUUID } from 'crypto';
async function localCode(email: string, recovery = false) {
  const dir = resolve('../backend/.mail-preview-e2e');
  for (const file of (await readdir(dir)).filter(f => f.endsWith('.eml')).sort().reverse()) {
    const mail = await readFile(resolve(dir, file), 'utf8');
    if (mail.includes(`To: ${email}\n`) && (!recovery || mail.includes('Recupera tu contraseña'))) return mail.match(/BAXIO es (\d{6})/)![1];
  } return '';
}
test('change and recover password with email OTP on mobile', async ({ page }, testInfo) => {
  test.setTimeout(90000);
  const email = `password-${randomUUID()}@example.invalid`, original = 'Original-password-927!', changed = 'Changed-password-428!', recovered = 'Recovered-password-953!';
  await page.addInitScript(() => localStorage.setItem('baxio-theme', 'dark'));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/auth/register');
  await page.getByLabel(/nombre completo/i).fill('Prueba contraseña');
  await page.getByLabel(/correo electrónico/i).fill(email);
  await page.getByLabel(/contraseña/i).fill(original);
  await page.getByRole('button', { name: /crear mi cuenta/i }).click();
  await expect(page.getByRole('heading', { name: 'Verifica tu correo' })).toBeVisible();
  await page.getByLabel('Código de verificación de 6 dígitos').fill(await localCode(email));
  await page.getByRole('button', { name: 'Verificar y continuar' }).click();
  await expect(page).toHaveURL('/');
  await page.goto('/profile/security');
  await page.getByRole('link', { name: /Cambiar contraseña/ }).click();
  await page.getByLabel('Contraseña actual', { exact: true }).fill('wrong-password');
  await page.getByLabel('Nueva contraseña', { exact: true }).fill(changed);
  await page.getByLabel('Confirmar nueva contraseña', { exact: true }).fill(recovered);
  await page.getByRole('button', { name: 'Guardar contraseña' }).click();
  await expect(page.getByRole('main').getByRole('alert')).toContainText('no coinciden');
  await page.getByLabel('Confirmar nueva contraseña', { exact: true }).fill(changed);
  await page.getByRole('button', { name: 'Guardar contraseña' }).click();
  await expect(page.getByRole('main').getByRole('alert')).toContainText(/contraseña/i);
  await page.getByLabel('Contraseña actual', { exact: true }).fill(original);
  await page.screenshot({ path: testInfo.outputPath('password-change-dark.png') });
  await page.getByRole('button', { name: 'Guardar contraseña' }).click();
  await expect(page.getByRole('heading', { name: 'Contraseña actualizada' })).toBeVisible();
  expect((await page.context().cookies()).find(c => c.name === 'access_token')).toBeUndefined();
  await page.goto('/auth/login');
  await page.getByRole('link', { name: 'Olvidé mi contraseña' }).click();
  await expect(page.getByRole('radio', { name: /SMS/ })).toBeDisabled();
  await page.getByRole('textbox', { name: 'Correo electrónico', exact: true }).fill(email);
  await page.getByRole('button', { name: 'Enviar código' }).click();
  await expect(page.getByRole('heading', { name: 'Verifica tu identidad' })).toBeVisible();
  await expect.poll(() => localCode(email, true)).toMatch(/^\d{6}$/);
  await page.getByLabel('Código de verificación de 6 dígitos').fill(await localCode(email, true));
  await page.screenshot({ path: testInfo.outputPath('password-otp-dark.png') });
  await page.getByRole('button', { name: 'Verificar código' }).click();
  await expect(page.getByLabel('Nueva contraseña', { exact: true })).toBeVisible();
  await page.getByLabel('Nueva contraseña', { exact: true }).fill(recovered);
  await page.getByLabel('Confirmar nueva contraseña', { exact: true }).fill(recovered);
  await page.getByRole('button', { name: 'Guardar contraseña' }).click();
  await expect(page.getByRole('heading', { name: 'Contraseña actualizada' })).toBeVisible();
  await page.goto('/auth/login');
  await page.getByLabel(/correo electrónico/i).fill(email);
  await page.getByLabel(/^contraseña$/i).fill(recovered);
  await page.getByRole('button', { name: /entrar a mi cuenta/i }).click();
  await expect(page).toHaveURL('/');
});
